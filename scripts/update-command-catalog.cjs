// Optional authoring helper. The checked-in catalog works without a build step.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const root = path.resolve(__dirname, "..");
const catalog = {};
const popular = ["format-json", "base64-encode", "url-encode", "uppercase"];
for (const [kind, directory, registry] of [
  ["text", "commands", "ScratchpadCommands"],
  ["sheet", "commands/cells", "ScratchpadCellCommands"],
]) {
  const context = vm.createContext({});
  vm.runInContext(fs.readFileSync(path.join(root, directory, "registry.js"), "utf8"), context);
  catalog[kind] = fs.readdirSync(path.join(root, directory))
    .filter((file) => file.endsWith(".js") && !["registry.js", "catalog.js", "loader.js"].includes(file))
    .sort()
    .map((file) => {
      vm.runInContext(fs.readFileSync(path.join(root, directory, file), "utf8"), context, { filename: file });
      const { id, name, description, category, icon, tags } = context[registry].all().at(-1);
      return { id, name, description, category, icon, tags, file: kind === "sheet" ? `cells/${file}` : file };
    });
  if (kind === "text") {
    const rank = (id) => popular.includes(id) ? popular.indexOf(id) : popular.length;
    catalog[kind].sort((left, right) => rank(left.id) - rank(right.id));
  }
}

const lists = Object.entries(catalog).map(([kind, commands]) =>
  `    ${kind}: [\n${commands.map((command) => `      ${JSON.stringify(command)},`).join("\n")}\n    ],`
).join("\n");
const source = `// Generated by node scripts/update-command-catalog.cjs; do not edit by hand.\n` +
  `(() => {\n  const catalog = {\n${lists}\n  };\n` +
  `  Object.values(catalog).forEach((commands) => {\n` +
  `    commands.forEach((command) => {\n` +
  `      command.searchText = [command.name, command.description, command.tags, command.category].join(" ").toLowerCase();\n` +
  `      Object.freeze(command);\n    });\n    Object.freeze(commands);\n  });\n` +
  `  globalThis.ScratchpadCommandCatalog = Object.freeze(catalog);\n})();\n`;
const target = path.join(root, "commands/catalog.js");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== source) {
    console.error("Command catalog is out of date. Run node scripts/update-command-catalog.cjs.");
    process.exitCode = 1;
  } else {
    console.log(`Command catalog matches all ${Object.values(catalog).flat().length} command definitions.`);
  }
} else {
  fs.writeFileSync(target, source);
  console.log(`Updated catalog for ${Object.values(catalog).flat().length} commands.`);
}
